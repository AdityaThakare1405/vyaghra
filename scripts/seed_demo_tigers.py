"""
Generates tiger territories using a correlated random walk — the standard
ecological model for real animal foraging movement (mostly continuing in a
consistent direction with occasional turns, unlike pure random noise or a
fixed mathematical formula shape).

The territory boundary is generated by buffering the actual walked path
into a polygon (like a thick, wobbly highlighter stroke along the route) —
this always produces a valid, non-empty, organic shape, unlike a concave
hull which can fail silently on sparse or clustered points.

Every step of the walk is checked against the real reserve boundary and
lake polygons via point-in-polygon tests, so no tiger can ever be placed
outside the reserve or inside the reservoir — enforced in code, not just
visually approximated.
"""

