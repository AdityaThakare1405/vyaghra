BEST_TIGERS_DIR = BASE_DIR / "data" / "samples" / "best_tigers"
KM_PER_DEG_LAT = 111.0


def km_per_deg_lon(lat):
    return 111.0 * math.cos(math.radians(lat))


with open(BASE_DIR / "data" / "samples" / "pench_boundary_approx.geojson") as f:
    _boundary_data = json.load(f)
    RESERVE_POLYGON = shape(_boundary_data["features"][0]["geometry"])

with open(BASE_DIR / "data" / "samples" / "pench_lake_approx.geojson") as f:
    _lake_data = json.load(f)
    LAKE_POLYGON = shape(_lake_data["features"][0]["geometry"])

print(f"Reserve polygon valid: {RESERVE_POLYGON.is_valid}, area: {RESERVE_POLYGON.area:.4f} sq deg")
print(f"Lake polygon valid: {LAKE_POLYGON.is_valid}")
_test_lat, _test_lon = 21.6716, 79.3033  # official park center — must be inside reserve
print(f"Official park center inside reserve: {RESERVE_POLYGON.contains(Point(_test_lon, _test_lat))}")

def is_valid_point(lat, lon):
    p = Point(lon, lat)
    return RESERVE_POLYGON.contains(p) and not LAKE_POLYGON.contains(p)

