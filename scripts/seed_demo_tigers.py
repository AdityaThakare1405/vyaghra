NEAREST_STATION = "ST-012"


def correlated_random_walk(start_lat, start_lon, n_steps, step_mean_km, turn_std_deg, seed_val):
    """
    Simulates real foraging movement (correlated random walk). Every
    candidate step is checked against the actual reserve/lake polygons;
    invalid steps are retried with a smaller, redirected step rather than
    just clamped to a box edge.
    """
    rng = random.Random(seed_val)
    lat, lon = start_lat, start_lon
    heading = rng.uniform(0, 360)
    points = [(lat, lon)]

    for _ in range(n_steps):
        placed = False
        attempts = 0
        while not placed and attempts < 15:
            turn = rng.gauss(0, turn_std_deg)
            candidate_heading = (heading + turn) % 360
            step_km = max(0.05, rng.expovariate(1.0 / step_mean_km)) * (0.6 ** attempts)

            rad = math.radians(candidate_heading)
            dlat = (step_km * math.cos(rad)) / KM_PER_DEG_LAT
            dlon = (step_km * math.sin(rad)) / km_per_deg_lon(lat)
            new_lat, new_lon = lat + dlat, lon + dlon

            if is_valid_point(new_lat, new_lon):
                lat, lon, heading = new_lat, new_lon, candidate_heading
                points.append((lat, lon))
                placed = True
            else:
                heading = (heading + 180 + rng.uniform(-40, 40)) % 360
                attempts += 1

        if not placed:
            # Couldn't find a valid step after 15 tries (rare, near a tight
            # corner) — just stay put this step rather than crash.
            points.append((lat, lon))

    return points


def seed():
    conn = get_connection()
    conn.execute("INSERT INTO runs (run_timestamp) VALUES (datetime('now'))")
    conn.commit()
    run_id = conn.execute("SELECT last_insert_rowid()").fetchone()[0]

    for real_tiger_id, profile in TIGER_PROFILES.items():
        tiger_folder = BEST_TIGERS_DIR / f"tiger_{real_tiger_id}"
        if not tiger_folder.exists():
            print(f"Skipping {real_tiger_id}: folder not found")
            continue

        vyaghra_tiger_id = f"T-{real_tiger_id}"
        display_name = profile["name"]
        start_lat, start_lon = profile["start"]

        if not is_valid_point(start_lat, start_lon):
            print(f"WARNING: {display_name}'s start point is invalid (outside reserve or in lake) — skipping")
            continue

        conn.execute(
            "INSERT OR REPLACE INTO tigers (tiger_id, first_enrolled_run_id, notes) VALUES (?, ?, ?)",
            (vyaghra_tiger_id, run_id, display_name),
        )
        conn.commit()

        walk_points = correlated_random_walk(
            start_lat, start_lon,
            profile["n_steps"], profile["step_mean_km"], profile["turn_std_deg"], profile["seed"],
        )

        # Buffer the walked path into a polygon — always valid, organic,
        # and directly reflects the tiger's actual simulated movement.
        path_line = LineString([(lon, lat) for lat, lon in walk_points])
        rng_width = random.Random(profile["seed"] + 777)
        buffer_deg = rng_width.uniform(0.010, 0.022)
        hull = path_line.buffer(buffer_deg, cap_style=1, join_style=1, resolution=8)
        hull = hull.simplify(0.002, preserve_topology=True)

        # Compute area in sq km via local equal-area approximation.
        area = 0.0
        if hull.geom_type == "Polygon" and not hull.is_empty:
            ref_lon, ref_lat = hull.exterior.coords[0]
            km_coords = [
                ((lon - ref_lon) * km_per_deg_lon(ref_lat), (lat - ref_lat) * KM_PER_DEG_LAT)
                for lon, lat in hull.exterior.coords
            ]
            area = abs(sum(
                km_coords[i][0] * km_coords[i + 1][1] - km_coords[i + 1][0] * km_coords[i][1]
                for i in range(len(km_coords) - 1)
            )) / 2.0
        elif hull.geom_type == "MultiPolygon" and not hull.is_empty:
            # Rare edge case: buffered path split into disconnected pieces.
            largest = max(hull.geoms, key=lambda g: g.area)
            hull = largest
            ref_lon, ref_lat = hull.exterior.coords[0]
            km_coords = [
                ((lon - ref_lon) * km_per_deg_lon(ref_lat), (lat - ref_lat) * KM_PER_DEG_LAT)
                for lon, lat in hull.exterior.coords
            ]
            area = abs(sum(
                km_coords[i][0] * km_coords[i + 1][1] - km_coords[i + 1][0] * km_coords[i][1]
                for i in range(len(km_coords) - 1)
            )) / 2.0

        rng = random.Random(profile["seed"] + 500)
        sighting_points = rng.sample(walk_points, min(20, len(walk_points)))

        images = sorted(tiger_folder.glob("*.jpg"))
        print(f"\n{display_name} ({vyaghra_tiger_id}): {len(walk_points)}-step walk, "
              f"{len(sighting_points)} sightings, area={area:.2f} sq km, geom_type={hull.geom_type}")

        for i, (plat, plon) in enumerate(sighting_points):
            img_path = images[i % len(images)]
            result = classify_image(str(img_path))
            fake_dt = datetime.now() - timedelta(days=random.randint(0, 45))

            cursor = conn.execute(
                """INSERT INTO images (original_path, station_id, capture_timestamp, timestamp_confidence,
                                        gps_lat, gps_lon, classification, classification_confidence, run_id)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (str(img_path), NEAREST_STATION, fake_dt.isoformat(), "synthetic",
                 plat, plon, result["label"], result["confidence"], run_id),
            )
            conn.commit()
            image_id = cursor.lastrowid

            conn.execute(
                """INSERT INTO sightings (image_id, tiger_id, match_confidence, decision_source, flank_usable)
                   VALUES (?, ?, ?, ?, ?)""",
                (image_id, vyaghra_tiger_id, result["confidence"], "human", 1),
            )
            conn.commit()

        if area > 0 and hull.geom_type == "Polygon" and not hull.is_empty:
            geojson_polygon = mapping(hull)
            conn.execute(
                """INSERT INTO occupancy_snapshots
                   (tiger_id, run_id, centroid_lat, centroid_lon, area_sq_km, home_range_geojson, station_list)
                   VALUES (?, ?, ?, ?, ?, ?, ?)""",
                (vyaghra_tiger_id, run_id, start_lat, start_lon, area, json.dumps(geojson_polygon), ""),
            )
            conn.commit()
        else:
            print(f"  WARNING: {display_name}'s polygon is empty/invalid — no occupancy snapshot saved")

    conn.close()
    print(f"\nSeeding complete. Run ID: {run_id}")
    return run_id


if __name__ == "__main__":
    seed()